# -*- coding: utf-8 -*-
"""文书临床序分桶 — 阶段(stage) → (桶名, 显示序).

把几百种「阶段」(大量是「某医师首次查房记录」) 用关键词归到 6 个临床文书桶 +
兜底「其他」, 让原文对照面板按临床阅读顺序分组折叠 (D3).

归桶用**关键词子串匹配**而非精确枚举 (因 阶段 有 783 种). `_LADDER` 的列表顺序
即匹配优先级 (首个命中关键词的桶胜出); 优先级用来解决冲突, 例如:
  - 「24小时入出院记录」含「出院记录」子串, 故入院桶须早于出院桶
  - 「疾病证明书」归出院 (含「疾病证明」), 而「职工…休假证明书」归知情 (含「证明书」)
  - 「手术知情同意书」「手术风险评估单」归知情而非手术 (知情桶早于手术桶)
  - 「术后情况告知书」「重大疑难手术申请报告单」归知情 (知情桶早于病程桶)

**显示顺序**由各桶的 `order` 字段决定 (病案首页1 → 入院2 → 病程3 → 手术4 → 知情5 →
出院6 → 其他99), 与匹配优先级**不同** —— 调用方按 `bucket_order` 排序即得临床阅读序.

Source: 本项目原创 (redesign-review-card-and-source).
"""

from __future__ import annotations

# (桶名, 显示序, 关键词元组) —— 列表顺序 = 匹配优先级 (首个命中胜出)
_LADDER: list[tuple[str, int, tuple[str, ...]]] = [
    ("病案首页", 1, ("病案首页", "康复病例首页")),
    # 入院须早于出院: 「入出院记录」含「出院记录」子串, 否则会被出院桶截走
    ("入院记录", 2, ("入院记录", "入出院记录")),
    # 出院须早于知情: 「疾病证明书」归出院 (而非知情的「证明书」); 死亡记录/小结一并归出院
    ("出院小结", 6, ("出院小结", "出院记录", "死亡", "疾病证明")),
    # 知情须早于手术 + 病程: 同意书/告知书/评估单/申请报告单等表单按后缀可靠识别,
    # 否则「手术知情同意书」「术后情况告知书」「重大疑难手术申请报告单」会被手术/病程截走
    ("知情书", 5, (
        "同意书", "告知书", "知情", "志愿书", "委托书", "证明书",
        "核查", "风险评估", "评估单", "评估表", "申请报告", "通知书", "谈话记录",
    )),
    ("手术记录", 4, ("手术记录", "操作记录", "PICC")),
    ("病程记录", 3, (
        "查房", "病程", "讨论", "小结", "术后", "术前", "疑难病例",
        "Tumor Board", "多学科", "危急值", "化疗病程", "输血", "转入", "转出",
        "评估记录", "阶段小结", "会诊", "抢救",
    )),
]

_OTHER: tuple[str, int] = ("其他", 99)


def bucket_of(stage: str | None) -> tuple[str, int]:
    """阶段 → (桶名, 显示序). 未命中任何关键词 → ('其他', 99). 永不丢行."""
    s = (stage or "").strip()
    if s:
        for name, order, keywords in _LADDER:
            for kw in keywords:
                if kw in s:
                    return name, order
    return _OTHER


def bucket_order_index() -> dict[str, int]:
    """{桶名: 显示序} (含 其他), 供前端 / 测试参照排序."""
    out = {name: order for name, order, _ in _LADDER}
    out[_OTHER[0]] = _OTHER[1]
    return out
